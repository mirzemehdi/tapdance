import { readFileSync } from "node:fs";
import { writeFile } from "node:fs/promises";
import { arch, homedir, platform, release } from "node:os";
import type { Command } from "commander";
import { redactSecrets, TESTED_SIMLOCK_VERSION, type DoctorCheck } from "@tapdance/sdk";
import { run, type GlobalOptions } from "./context.js";

const pkg = JSON.parse(readFileSync(new URL("../package.json", import.meta.url), "utf8")) as { version: string; dependencies: Record<string, string> };

/**
 * `tapdance report`: an issue-ready Markdown body with everything a maintainer needs and nothing
 * secret. A field-testing agent fills in what happened and files it with `gh issue create`.
 */
export function registerReportCommand(program: Command, globals: () => GlobalOptions): void {
  program
    .command("report")
    .description("Write a redacted, issue-ready bug report (environment, versions, doctor, lease) to stdout or a file")
    .option("--title <text>", "one-line summary")
    .option("--kind <kind>", "bug | missing-feature | docs | field-test", "bug")
    .option("--steps <text>", "what you ran, in order")
    .option("--expected <text>", "what should have happened")
    .option("--actual <text>", "what happened instead (paste the error)")
    .option("--evidence <paths>", "comma-separated artifact paths (screenshots, logs) to list")
    .option("-o, --output <file>", "write to this file (for `gh issue create --body-file`)")
    .action(async (o: { title?: string; kind: string; steps?: string; expected?: string; actual?: string; evidence?: string; output?: string }) =>
      run(
        globals(),
        async (t, out) => {
          const checks: DoctorCheck[] = await t.doctor().catch((error: Error) => [{ id: "doctor", title: "doctor", status: "fail" as const, detail: error.message }]);
          const record = await t.current();
          const cfg = t.resolved.config;
          const body = [
            `## ${o.title ?? "Summary"}`,
            "",
            `**Kind:** ${o.kind}`,
            "",
            "### Steps to reproduce",
            o.steps ?? "1. …",
            "",
            "### Expected",
            o.expected ?? "…",
            "",
            "### Actual",
            o.actual ? "```text\n" + o.actual + "\n```" : "…",
            "",
            "### Environment",
            `- tapdance ${pkg.version} (simlock ${pkg.dependencies["simlock"]}, agent-device ${pkg.dependencies["agent-device"]}; tested with simlock ${TESTED_SIMLOCK_VERSION})`,
            `- Node ${process.versions.node} on ${platform()} ${release()} ${arch()}`,
            `- provider: ${cfg.provider}${cfg.endpoint ? ` (endpoint host: ${new URL(cfg.endpoint).host})` : ""}; iOS UI backend: ${cfg.ios.uiBackend}`,
            `- session source: ${t.session.source}`,
            record
              ? `- lease: ${record.handle.platform} ${record.handle.model} ${record.handle.osVersion} on ${record.handle.location.kind} worker ${record.handle.location.workerLabel ?? record.handle.location.workerId ?? ""} (owner ${record.owner?.kind ?? "?"})`
              : "- lease: none",
            "",
            "### Doctor",
            "```text",
            ...checks.map((c) => `${c.status.toUpperCase().padEnd(4)} ${c.title} — ${c.detail}`),
            "```",
            ...(o.evidence ? ["", "### Evidence", ...o.evidence.split(",").map((p) => `- \`${p.trim()}\``), "", "_Attach the files above to the issue; paths are on the reporter's machine._"] : []),
            "",
            "<sub>Generated by `tapdance report`. Tokens are redacted; check the text before posting.</sub>",
          ].join("\n");
          // Paths name the reporter's account; keep them readable but anonymous.
          const safe = redactSecrets(body).split(homedir()).join("~");
          if (o.output) {
            await writeFile(o.output, `${safe}\n`);
            out.result({ written: o.output }, () => `Wrote ${o.output}\nFile it with: gh issue create --title "${o.title ?? "…"}" --body-file ${o.output} --label ${o.kind}`);
          } else {
            out.result({ title: o.title ?? null, kind: o.kind, body: safe }, () => safe);
          }
        },
        { fleet: false },
      ),
    );
}
